import { ok, done } from './t-lib.mjs';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const tool = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dd-open-'));
fs.writeFileSync(path.join(root, 'doc.md'), '# Plan\n\nHello\n\n<!-- tab: Two -->\nSecond tab\n');
const run = (...a) => spawnSync(process.execPath, [path.join(tool, 'open-doc.mjs'), root, '--port', '4290', ...a], { encoding: 'utf8' });
const r = run('--ds', 'tu');
ok(/OPEN: http:\/\/localhost:\d+\/doc\.html/.test(r.stdout), 'prints the address', r.stdout + r.stderr);
const url = /OPEN: (\S+)/.exec(r.stdout)?.[1];
const page = await (await fetch(url)).text();
ok(page.includes('data-title="Plan"') && page.includes('data-tab="t2"') && page.includes('ds-tu.js'), 'serves the built doc');
ok((await fetch(url.replace('doc.html', 'editor.js'))).status === 200 && (await fetch(url.replace('doc.html', 'ds-tu.js'))).status === 200, 'serves editor files from the tool folder');
fs.writeFileSync(path.join(root, 'doc.html'), page.replace('Hello', 'Edited in editor'));
const r2 = run(); ok(/already running/.test(r2.stdout), 'second call reuses the server');
fs.writeFileSync(path.join(root, 'doc.md'), '# Plan\n\nChanged source\n');
run('--no-serve'); ok(fs.readFileSync(path.join(root, 'doc.html'), 'utf8').includes('Edited in editor'), 'existing doc.html is kept without --rebuild');
run('--no-serve', '--rebuild'); ok(fs.readFileSync(path.join(root, 'doc.html'), 'utf8').includes('Changed source'), '--rebuild rebuilds from Markdown');
const r3 = run('--stop'); ok(/stopped server/.test(r3.stdout), 'stop works', r3.stdout);
await new Promise(r => setTimeout(r, 300));
ok(await fetch(url).then(() => false, () => true), 'server is gone after stop');
fs.rmSync(root, { recursive: true, force: true });
await done();
