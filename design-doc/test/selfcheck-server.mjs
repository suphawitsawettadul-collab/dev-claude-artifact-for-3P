import fs from 'node:fs';
import { ok, done } from './t-lib.mjs';
const base = 'http://localhost:' + process.env.PORT;
const g = async p => (await fetch(base + p)).status;
ok(await g('/doc.html') === 200, 'serves doc.html');
ok(await g('/editor.js') === 200 && await g('/editor.css') === 200 && await g('/ds-tu.js') === 200, 'serves editor files');
ok(await g('/..%2Fserve.mjs') === 400, 'blocks ../');
ok(await g('/a%5Cb.html') === 400, 'blocks backslash');
ok(await g('/nope.html') === 404, '404 for missing');
const post = async (f, body) => (await fetch(base + '/save?file=' + encodeURIComponent(f), { method: 'POST', body })).status;
ok(await post('x.exe', 'a') === 400, 'refuses other extensions');
ok(await post('../x.html', 'a') === 400, 'refuses paths in file name');
ok(await post('s.md', '# hi') === 200 && fs.readFileSync(process.env.DOC_DIR + '/s.md', 'utf8') === '# hi', 'saves a .md');
const s1 = await (await fetch(base + '/stamp?file=s.md')).text();
await new Promise(r => setTimeout(r, 20)); await post('s.md', '# hi2');
ok(await (await fetch(base + '/stamp?file=s.md')).text() !== s1, 'stamp changes after a write');
ok(await (await fetch(base + '/stamp?file=missing.md')).text() === '0', 'stamp is 0 for a missing file');
await post('doc2.html', 'v1'); await post('doc2.html', 'v2');
ok(fs.readFileSync(process.env.DOC_DIR + '/doc2.html.bak', 'utf8') === 'v1', '.html save keeps one .bak');
await done();
