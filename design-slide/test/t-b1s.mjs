// B1 text-style dropdown: Theme / Custom tabs, search, apply, undo; built-in styles without a design system.
import { start, ok } from './t-lib.mjs';
import * as L from './t-lib.mjs';
import * as H from './t-bh.mjs';
await start('http://localhost:' + process.env.PORT + '/tu-test.html#4');
const b = L.b, SUB = '.slide.active .tu-sub';
const lbl = () => b.ev(`document.querySelector('#ed-tb [data-tb=style]').textContent`);
await L.clickOn(SUB);
ok((await lbl()).includes('subtitle'), 'current style from size + weight (subtitle 36/400)', await lbl());
await H.tbClick('style');
ok(await H.popOpen(), 'style popover opens');
ok(await b.ev(`[...document.querySelectorAll('#ed-pop .ed-tabs button')].map(x => x.textContent).join('|')`) === 'Theme|Custom', 'tabs Theme | Custom');
ok(await b.ev(`!!document.querySelector('#ed-pop input.ed-q')`), 'search box');
ok(await b.ev(`document.querySelector('#ed-pop .ed-h').textContent`) === 'Thai Union 01', 'bold heading with the DS name');
ok(await b.ev(`[...document.querySelectorAll('#ed-pop .ed-lbl')].map(n => n.textContent).join('|')`) === 'Cover|Gradient slides|Content', 'group labels');
ok(await b.ev(`document.querySelectorAll('#ed-pop [data-s]').length`) === 13, '13 styles');
const row = await b.ev(`(() => { const r = document.querySelector('#ed-pop [data-s=cover-title]'); return [r.querySelector('span').textContent + ' ' + r.querySelector('em').textContent, getComputedStyle(r).fontWeight]; })()`);
ok(row[0] === 'cover-title 80' && row[1] === '700', 'row drawn in its weight with the size after it', JSON.stringify(row));
ok(await b.ev(`document.querySelector('#ed-pop [data-s=subtitle]').classList.contains('on') && !!document.querySelector('#ed-pop [data-s=subtitle] svg')`), 'check mark on the current style');
await L.clickOn('#ed-pop input.ed-q'); await b.type('cover');
ok(await b.ev(`document.querySelectorAll('#ed-pop [data-s]').length`) === 3, 'search narrows the list');
await b.key('a', { ctrl: true }); await b.key('Backspace', { code: 'Backspace', vk: 8 });
ok(await b.ev(`document.querySelectorAll('#ed-pop [data-s]').length`) === 13, 'search cleared');
await H.pClick('[data-s=body]');
ok(!(await H.popOpen()), 'popover closes after a pick');
ok((await b.ev(`(e => [e.style.fontSize, e.style.fontWeight, e.dataset.style].join('|'))(document.querySelector('${SUB}'))`)) === '28px|400|body', 'style written inline + data-style');
ok((await b.ev(`document.querySelector('#ed-tb [data-tb=style]').textContent`)).includes('body'), 'toolbar shows the new style');
await H.undo();
ok(await b.ev(`document.querySelector('${SUB}').dataset.style`) === undefined && await H.style(SUB, 'fontSize') === '', 'Ctrl+Z restores the style');
await H.redo();
ok(await b.ev(`document.querySelector('${SUB}').dataset.style`) === 'body', 'redo applies it again');
await L.clickOn(SUB);
await b.ev(`DeckEditor.change(() => { const e = document.querySelector('${SUB}'); e.style.fontSize = '50px'; delete e.dataset.style; })`);
ok((await lbl()).includes('Custom') && (await lbl()).includes('50'), 'no match: Custom + size', await lbl());
await H.tbClick('style'); await L.clickOn('#ed-pop [data-tab=custom]');
const fam = await b.ev(`[...document.querySelectorAll('#ed-pop #ed-f-fam option')].map(o => o.textContent).join()`);
ok(fam === 'Figtree,Sans-serif,Serif,Monospace', 'custom: DS font + generic families', fam);
ok(await b.ev(`document.querySelector('#ed-pop #ed-f-size').value`) === '50' && await b.ev(`!!document.querySelector('#ed-pop #ed-f-w')`), 'custom: size input + weight select');
await L.clickOn('#ed-pop #ed-f-size'); await b.key('a', { ctrl: true }); await b.type('33');
ok(await H.style(SUB, 'fontSize') === '33px', 'size input applies', await H.style(SUB, 'fontSize'));
await b.ev(`document.activeElement.blur()`); await H.undo(); // focus left the input: Ctrl+Z is the deck's undo
ok(await H.style(SUB, 'fontSize') === '50px', 'one Ctrl+Z undoes the typed size (ticks merged)', await H.style(SUB, 'fontSize'));
await L.clickOn(SUB); await H.tbClick('style'); await L.clickOn('#ed-pop [data-tab=custom]');
await b.ev(`(s => { s.value = '700'; s.dispatchEvent(new Event('change', { bubbles: true })); })(document.querySelector('#ed-pop #ed-f-w'))`);
await b.ev(`(s => { s.selectedIndex = 2; s.dispatchEvent(new Event('change', { bubbles: true })); })(document.querySelector('#ed-pop #ed-f-fam'))`);
ok((await H.style(SUB, 'fontFamily')).includes('Georgia') && await H.style(SUB, 'fontWeight') === '700', 'family + weight apply');
await b.key('Escape', { code: 'Escape', vk: 27 });
ok(!(await H.popOpen()), 'Esc closes the popover');
ok((await b.ev(`DeckEditor.selection.length`)) === 1, 'Esc closed only the popover, selection kept');
console.log(b.logs.join('\n')); console.log('B1 style done', L.passes, 'pass', L.fails, 'fail');
await b.close();
