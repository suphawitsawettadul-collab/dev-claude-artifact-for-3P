import { start, ok } from './t-lib.mjs';
import * as L from './t-lib.mjs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = fileURLToPath(new URL('.', import.meta.url));
const png = path.resolve(here, '../tu-bg-agenda.png');
await start('http://localhost:' + process.env.PORT + '/tu-test.html#4');
const b = L.b;
const doc = await b.send('DOM.getDocument');
const inp = await b.send('DOM.querySelector', { nodeId: doc.result.root.nodeId, selector: '#ed-file' });
await b.send('DOM.setFileInputFiles', { files: [png], nodeId: inp.result.nodeId });
await b.sleep(800);
const s = await L.S();
ok(s.length === 1 && s[0].startsWith('img:'), 'inserted image is selected as img', JSON.stringify(s));
const [x, y] = await L.at('.slide.active img.ed-free');
const r0 = await b.ev(`JSON.stringify(document.querySelector('.slide.active img.ed-free').getBoundingClientRect())`);
await b.drag(x, y, x + 50, y + 20);
const r1 = await b.ev(`JSON.stringify(document.querySelector('.slide.active img.ed-free').getBoundingClientRect())`);
ok(JSON.parse(r1).left - JSON.parse(r0).left > 40, 'image moves', r0 + r1);
await b.key('z', { ctrl: true });
await b.key('z', { ctrl: true });
ok(await b.ev(`document.querySelectorAll('.slide.active img.ed-free').length`) === 0, 'two undos remove the image (move, insert)');
console.log(b.logs.join('\n')); console.log('img', L.passes, 'pass', L.fails, 'fail');
await b.close();
