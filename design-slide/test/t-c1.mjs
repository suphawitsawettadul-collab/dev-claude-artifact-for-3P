// C1: the panel toggles from the top-right button and from the toolbar dots, remembers open / closed, lists its sections,
// follows the selection live, and shows slide properties when nothing (or the slide) is selected.
import { start, ok } from './t-lib.mjs';
import * as L from './t-lib.mjs';
import * as C from './t-ch.mjs';
await start('http://localhost:' + process.env.PORT + '/tu-test.html#4');
const b = L.b, TITLE = '.slide.active .tu-title', SUB = '.slide.active .tu-sub';
const tbBox = () => b.ev(`(() => { const t = document.getElementById('ed-tb'), r = t.getBoundingClientRect(); return { on: t.style.display === 'flex', l: r.left, r: r.right }; })()`);
ok(!(await b.ev('DeckEditor.panelOpen')) && await b.ev(`getComputedStyle(document.getElementById('ed-panel')).display`) === 'none', 'panel starts closed');
const st0 = await C.rect('#stage');
await L.clickOn('#ed-pp');
ok(await b.ev('DeckEditor.panelOpen'), 'top-right button opens the panel');
const pn = await C.rect('#ed-panel'), st1 = await C.rect('#stage');
ok(C.near(st0.w - st1.w, pn.w, 2) && st1.r <= pn.l + 1, 'stage shrinks to make room for the panel', JSON.stringify([st0, st1, pn]));
ok(await b.ev(`document.getElementById('ed-pp').title`) === 'Hide properties', 'tooltip follows the state');
ok(await C.title() === 'Slide' && (await C.secs()).join() === 'Slide,Layout,Transition', 'nothing selected: slide properties', (await C.secs()).join());
ok(await b.ev(`!!document.querySelector('#ed-panel .pp-head .pp-x')`), 'header row with a close button');
await L.clickOn(TITLE);
ok(await C.title() === 'Text', 'header names the selection');
ok((await C.secs()).join() === 'Size,Layout,Text,Appearance,Effects,Advanced', 'text sections', (await C.secs()).join());
ok(await b.ev(`[...document.querySelectorAll('#pp-body .pp-sec')].map(s => s.querySelector('.pp-st .pp-ic')?.dataset.act || '-').join()`) === '-,-,textMore,-,fxMenu,adv', 'Text and Effects have +, Advanced has the arrow');
const t = await tbBox();
ok(t.on && t.r <= (await C.rect('#stage')).r + 1, 'floating toolbar stays inside the shrunken stage', JSON.stringify(t));
ok(await C.pv('fs') === '56' && await C.pv('w') === '1776', 'font size and width of .tu-title', await C.pv('fs') + ' ' + await C.pv('w'));
await L.clickOn(SUB, {}, 330);
ok(await C.pv('fs') === '36' && await C.ptext('ts') === 'subtitle', 'selecting the subtitle updates the panel', await C.pv('fs') + await C.ptext('ts'));
const w0 = +await C.pv('w');
const hs = await b.ev(`(() => { const r = document.querySelector('.slide.active .ed-sel i[data-h=se]').getBoundingClientRect(); return [r.left + r.width / 2, r.top + r.height / 2]; })()`);
await b.drag(hs[0], hs[1], hs[0] - 100, hs[1]);
ok(+await C.pv('w') < w0 - 100, 'resizing with a handle updates Width live', w0 + ' -> ' + await C.pv('w'));
await C.undo(); await L.clickOn(SUB);
ok(C.near(+await C.pv('w'), w0, 1.5), 'undo brings the old width back in the panel', await C.pv('w'));
await L.clickOn('#ed-tb [data-tb=more]');
ok(!(await b.ev('DeckEditor.panelOpen')), 'toolbar dots close an open panel');
await L.clickOn('#ed-tb [data-tb=more]');
ok(await b.ev('DeckEditor.panelOpen'), 'and open it again');
await L.esc();
const [sx, sy, sw, sh] = await L.sc();
await b.click(sx + sw * 0.15, sy + sh * 0.75);
ok((await L.S())[0].startsWith('slide:') && await C.title() === 'Slide' && await C.has('[data-pp=bg]'), 'slide selected: slide properties with Background');
ok(await b.ev(`document.querySelector('#pp-body select[disabled]') !== null`), 'Transition placeholder row');
await b.ev('setTimeout(() => location.reload(), 10)'); await b.sleep(2500);
ok(await b.ev('DeckEditor.panelOpen') && await b.ev(`localStorage.getItem('deck-ed:panel')`) === '1', 'open state remembered in localStorage');
await L.clickOn('#ed-panel .pp-x');
ok(!(await b.ev('DeckEditor.panelOpen')) && !(await b.ev(`localStorage.getItem('deck-ed:panel')`)), 'close button closes and forgets');
await C.openPanel(); await b.ev(`document.querySelector('[data-cmd=theme]').click()`);
const bg = await C.comp('#ed-panel', 'backgroundColor'), inp = await b.ev(`getComputedStyle(document.querySelector('#pp-body .pp-in')).backgroundColor`);
ok(bg === 'rgb(251, 251, 250)' && inp === 'rgb(241, 241, 239)', 'light mode colours come from the theme tokens', bg + ' ' + inp);
await b.ev(`document.querySelector('[data-cmd=theme]').click()`);
console.log(b.logs.join('\n')); console.log('C1 panel done', L.passes, 'pass', L.fails, 'fail');
await b.close();
